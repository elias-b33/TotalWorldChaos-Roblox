"""Convert assets/maps/<map>/layout.json into src/shared/MapData/<Map>.luau.

    python3 tools/mapgen/export_luau.py      # all maps, from the existing layout.json files

generate.py also calls this after every map build, so the Luau data never drifts from the JSON.
"""

from __future__ import annotations

import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
OUT = os.path.join(ROOT, "src", "shared", "MapData")

MODULE_NAMES = {"earth": "Earth", "eldmoor": "Eldmoor", "skyshards": "Skyshards"}


def lua_str(s: str) -> str:
    out = []
    for ch in s:
        if ch in '"\\':
            out.append("\\" + ch)
        elif 32 <= ord(ch) < 127:
            out.append(ch)
        else:
            out.append("\\u{%x}" % ord(ch))
    return '"' + "".join(out) + '"'


def point(p) -> str:
    return "{ x = %d, y = %d }" % (round(p[0]), round(p[1]))


def ids(xs) -> str:
    return "{ " + ", ".join(str(x) for x in xs) + " }" if xs else "{}"


def nums(xs) -> str:
    return "{ " + ", ".join(f"{x:g}" for x in xs) + " }" if xs else "{}"


def to_luau(layout: dict) -> str:
    key = layout["id"]
    lines = [
        "--!strict",
        f"-- GENERATED by tools/mapgen/export_luau.py from assets/maps/{key}/layout.json. Do not edit:",
        "-- change tools/mapgen and run `python3 tools/mapgen/generate.py` instead.",
        "",
        'local Types = require("../Types")',
        "",
        "local map: Types.MapDef = {",
        f"\tid = {lua_str(key)},",
        f"\ttitle = {lua_str(layout['title'])},",
        f"\ttheme = {lua_str(layout['theme'])},",
        f"\timageSize = {point(layout['imageSize'])},",
        "\tnations = {",
    ]
    for n in layout["nations"]:
        lines.append(
            f"\t\t{{ slot = {n['slot']}, name = {lua_str(n['name'])}, capital = {n['capital']}, colorIndex = {n['colorIndex']} }},"
        )
    lines.append("\t},")
    lines.append("\tprovinces = {")
    for i, p in enumerate(layout["provinces"]):
        assert p["id"] == i + 1, "province ids must be 1..N in order"
        fields = [
            f"id = {p['id']}",
            f"name = {lua_str(p['name'])}",
            f"terrain = {lua_str(p['terrain'])}",
            f"biome = {lua_str(p['biome'])}",
            f"development = {p['development']}",
            f"neighbors = {ids(p['neighbors'])}",
            f"center = {point(p['center'])}",
            f"area = {p['area']}",
        ]
        if p.get("startOwner") is not None:
            fields.append(f"startOwner = {p['startOwner']}")
        fields.append(f"isCapital = {'true' if p['isCapital'] else 'false'}")
        if p.get("garrison"):
            fields.append(f"garrison = {p['garrison']}")
        fields.append(f"tris = {nums(p.get('tris', []))}")
        lines.append("\t\t{ " + ", ".join(fields) + " },")
    lines.append("\t},")
    lines.append("\tstraits = {")
    for s in layout["straits"]:
        lines.append(
            f"\t\t{{ a = {s['a']}, b = {s['b']}, from = {point(s['from'])}, to = {point(s['to'])}, "
            f"wrap = {'true' if s['wrap'] else 'false'} }},"
        )
    lines.append("\t},")
    lines.append("\tborders = {")
    for b in layout.get("borders", []):
        lines.append(f"\t\t{{ a = {b['a']}, b = {b['b']}, points = {nums(b['points'])} }},")
    lines.append("\t},")
    lines.append("}")
    lines.append("")
    lines.append("return map")
    lines.append("")
    return "\n".join(lines)


def write(layout: dict) -> str:
    os.makedirs(OUT, exist_ok=True)
    path = os.path.join(OUT, MODULE_NAMES[layout["id"]] + ".luau")
    with open(path, "w") as f:
        f.write(to_luau(layout))
    return path


def main() -> None:
    for key in MODULE_NAMES:
        with open(os.path.join(ROOT, "assets", "maps", key, "layout.json")) as f:
            print("wrote", os.path.relpath(write(json.load(f)), ROOT))


if __name__ == "__main__":
    main()
