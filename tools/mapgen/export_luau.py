"""Convert assets/maps/<map>/layout.json into src/shared/MapData/<Map>.luau.

    python3 tools/mapgen/export_luau.py      # all maps, from the existing layout.json files

generate.py also calls this after every map build, so the Luau data never drifts from the JSON.

Besides the JSON, each module carries the map's province grid (`grid`): which province every pixel of the 2D
pixel-art map belongs to, at half the resolution of province_ids.png (1 grid pixel = 2x2 map pixels = 1 stud).
It is run-length encoded as (id: u8, length: u16 little-endian) triples over the rows top to bottom, in base64.
"""

from __future__ import annotations

import base64
import json
import os
import struct

import numpy as np
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
OUT = os.path.join(ROOT, "src", "shared", "MapData")

MODULE_NAMES = {"earth": "Earth", "eldmoor": "Eldmoor", "skyshards": "Skyshards"}


def lua_str(s: str) -> str:
    out = []
    for ch in s:
        if ch in '"\\':
            out.append("\\" + ch)
        elif 32 <= ord(ch) < 127:
            out.append(ch)
        else:
            out.append("\\u{%x}" % ord(ch))
    return '"' + "".join(out) + '"'


def point(p) -> str:
    return "{ x = %d, y = %d }" % (round(p[0]), round(p[1]))


def ids(xs) -> str:
    return "{ " + ", ".join(str(x) for x in xs) + " }" if xs else "{}"


GRID_STEP = 2  # map pixels per grid pixel


def grid_of(ids_path: str) -> tuple[int, int, str]:
    """(width, height, base64 RLE) of the province grid from province_ids.png (id = R + 256 * G)."""
    rgb = np.asarray(Image.open(ids_path).convert("RGB")).astype(np.int64)
    ids = (rgb[..., 0] + 256 * rgb[..., 1])[::GRID_STEP, ::GRID_STEP]
    assert ids.max() < 256, "grid ids must fit in one byte"
    flat = ids.ravel()
    starts = np.concatenate([[0], np.flatnonzero(np.diff(flat)) + 1])
    ends = np.concatenate([starts[1:], [flat.size]])
    out = bytearray()
    for a, b in zip(starts, ends):
        n = int(b - a)
        while n > 0:
            take = min(n, 0xFFFF)
            out += struct.pack("<BH", int(flat[a]), take)
            n -= take
    return ids.shape[1], ids.shape[0], base64.b64encode(bytes(out)).decode("ascii")


def to_luau(layout: dict, ids_path: str) -> str:
    key = layout["id"]
    lines = [
        "--!strict",
        f"-- GENERATED by tools/mapgen/export_luau.py from assets/maps/{key}/layout.json. Do not edit:",
        "-- change tools/mapgen and run `python3 tools/mapgen/generate.py` instead.",
        "",
        'local Types = require("../Types")',
        "",
        "local map: Types.MapDef = {",
        f"\tid = {lua_str(key)},",
        f"\ttitle = {lua_str(layout['title'])},",
        f"\ttheme = {lua_str(layout['theme'])},",
        f"\timageSize = {point(layout['imageSize'])},",
        "\tnations = {",
    ]
    for n in layout["nations"]:
        lines.append(
            f"\t\t{{ slot = {n['slot']}, name = {lua_str(n['name'])}, capital = {n['capital']}, "
            f"colorIndex = {n['colorIndex']}, race = {lua_str(n['race'])} }},"
        )
    lines.append("\t},")
    lines.append("\tprovinces = {")
    for i, p in enumerate(layout["provinces"]):
        assert p["id"] == i + 1, "province ids must be 1..N in order"
        fields = [
            f"id = {p['id']}",
            f"name = {lua_str(p['name'])}",
            f"terrain = {lua_str(p['terrain'])}",
            f"biome = {lua_str(p['biome'])}",
            f"development = {p['development']}",
            f"neighbors = {ids(p['neighbors'])}",
            f"center = {point(p['center'])}",
            f"area = {p['area']}",
        ]
        if p.get("startOwner") is not None:
            fields.append(f"startOwner = {p['startOwner']}")
        fields.append(f"isCapital = {'true' if p['isCapital'] else 'false'}")
        if p.get("garrison"):
            fields.append(f"garrison = {p['garrison']}")
        lines.append("\t\t{ " + ", ".join(fields) + " },")
    lines.append("\t},")
    lines.append("\tstraits = {")
    for s in layout["straits"]:
        lines.append(
            f"\t\t{{ a = {s['a']}, b = {s['b']}, from = {point(s['from'])}, to = {point(s['to'])}, "
            f"wrap = {'true' if s['wrap'] else 'false'} }},"
        )
    lines.append("\t},")
    width, height, rle = grid_of(ids_path)
    lines.append(f'\tgrid = {{ width = {width}, height = {height}, rle = "{rle}" }},')
    lines.append("}")
    lines.append("")
    lines.append("return map")
    lines.append("")
    return "\n".join(lines)


def write(layout: dict) -> str:
    os.makedirs(OUT, exist_ok=True)
    path = os.path.join(OUT, MODULE_NAMES[layout["id"]] + ".luau")
    ids_path = os.path.join(ROOT, "assets", "maps", layout["id"], "province_ids.png")
    with open(path, "w") as f:
        f.write(to_luau(layout, ids_path))
    return path


def main() -> None:
    for key in MODULE_NAMES:
        with open(os.path.join(ROOT, "assets", "maps", key, "layout.json")) as f:
            print("wrote", os.path.relpath(write(json.load(f)), ROOT))


if __name__ == "__main__":
    main()
